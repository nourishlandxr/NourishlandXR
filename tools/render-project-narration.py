import asyncio,json,pathlib,sys,subprocess,os
root=pathlib.Path(__file__).resolve().parents[1]
runtime=os.environ.get('NXR_SPEECH_RUNTIME')
if runtime:sys.path.insert(0,runtime)
import edge_tts
work=root/'.tmp/project-narration';dest=root/'app/assets/project-narration';dest.mkdir(parents=True,exist_ok=True)
clips=json.loads((work/'catalog.json').read_text(encoding='utf-8-sig'));gate=asyncio.Semaphore(3)
async def render(clip):
 async with gate:
  target=dest/(clip['id']+'.mp3')
  if target.exists() and target.stat().st_size>1000:return
  source=work/(clip['id']+'-source.mp3')
  for attempt in range(3):
   try:
    await edge_tts.Communicate(clip['spoken'],'en-US-AvaMultilingualNeural',rate='+0%',pitch='+0Hz').save(str(source));break
   except Exception:
    if attempt==2:raise
    await asyncio.sleep(2+attempt*3)
  subprocess.run(['C:/Program Files/Virtual Desktop Streamer/ffmpeg.exe','-hide_banner','-loglevel','error','-y','-i',str(source),'-af','highpass=f=65,deesser=i=0.12:m=0.18:f=0.5','-ar','24000','-ac','1','-codec:a','libmp3lame','-b:a','128k',str(target)],check=True)
  print('Recorded '+clip['id'],flush=True)
async def main():
 await asyncio.gather(*(render(c) for c in clips))
 entries={c['id']:{'text':c['text'],'file':c['id']+'.mp3'} for c in clips}
 (root/'app/services/projectNarrationCatalog.js').write_text('// Generated by tools/build-project-narration.mjs and tools/render-project-narration.py.\nexport const PROJECT_NARRATION_CATALOG=Object.freeze('+json.dumps(entries,ensure_ascii=False,separators=(',',':'))+');\n',encoding='utf-8')
 print('Recorded all '+str(len(clips))+' paragraphs.',flush=True)
asyncio.run(main())
