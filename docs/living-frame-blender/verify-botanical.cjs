// Real asset/interaction verification, independent of Blender authoring internals.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base='http://127.0.0.1:8769';
(async()=>{
 const bytes=fs.readFileSync(path.join(__dirname,'botanical-section.glb'));
 assert.equal(bytes.toString('ascii',0,4),'glTF');
 const jsonLength=bytes.readUInt32LE(12);
 const asset=JSON.parse(bytes.toString('utf8',20,20+jsonLength));
 assert.equal(asset.animations.length,1,'Growth should export as one synchronized clip');
 assert.equal(asset.images.length,4,'Soil colours, soil normals and leaf veins must be embedded');
 assert.ok(asset.images.every(image=>Number.isInteger(image.bufferView)));
 assert.ok(!asset.cameras?.length);
 assert.ok(asset.nodes.every(node=>!(/REFERENCE|Take a moment|look around|clearance/i.test(node.name||''))));
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 try{
  const page=await browser.newPage({viewport:{width:1400,height:1100}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/docs/living-frame-blender/preview.html?model=botanical');
  await page.waitForSelector('body[data-model-ready="true"]',{timeout:30000});
  const stats=await page.evaluate(()=>window.ringReview);
  assert.equal(stats.animations,1);assert.ok(stats.meshes>10);assert.equal(stats.shootScales.length,3);
  assert.ok(stats.minRadius>.80,'Actual geometry must stay outside the protected reading disc');
  assert.ok(stats.shootScales.every(value=>value>.99),'Mature new shoots must be full size');
  await page.screenshot({path:path.join(__dirname,'botanical-preview-perspective.png')});
  await page.locator('[data-view="detail"]').click();await page.waitForTimeout(600);
  await page.screenshot({path:path.join(__dirname,'botanical-preview-detail.png')});
  const mature=await page.locator('#view canvas').screenshot();
  const matureHinges=await page.evaluate(()=>window.ringReview.leafHinges);
  assert.equal(matureHinges.length,6);
  await page.locator('#growth').press('Home');await page.waitForTimeout(150);
  assert.ok((await page.evaluate(()=>window.ringReview.shootScales)).every(value=>value<.03));
  assert.notDeepEqual(await page.evaluate(()=>window.ringReview.leafHinges),matureHinges,'Leaves must unfold around their hinges');
  const beginning=await page.locator('#view canvas').screenshot();
  assert.ok(!mature.equals(beginning),'Exported growth must visibly change foliage');
  await page.screenshot({path:path.join(__dirname,'botanical-growth-start.png')});
  await page.locator('#replay').click();await page.waitForTimeout(900);
  assert.equal(await page.evaluate(()=>window.ringReview.playing),true);
  assert.ok((await page.evaluate(()=>window.ringReview.growthTime))>.4);
  await page.locator('#pause').click();
  const paused=await page.evaluate(()=>window.ringReview.growthTime);await page.waitForTimeout(350);
  assert.equal(await page.evaluate(()=>window.ringReview.growthTime),paused);
  await page.locator('#growth').evaluate(input=>{input.value='18';input.dispatchEvent(new Event('input',{bubbles:true}));});
  assert.equal(await page.evaluate(()=>window.ringReview.growthTime),18);
  await page.locator('#mature').click();
  assert.ok((await page.evaluate(()=>window.ringReview.shootScales)).every(value=>value>.99));
  assert.equal(await page.evaluate(()=>window.ringReview.playing),false);
  await page.locator('[data-view="side"]').click();await page.waitForTimeout(600);
  await page.screenshot({path:path.join(__dirname,'botanical-preview-side.png')});
  assert.deepEqual(errors,[]);
  const version=fs.readFileSync(path.join(__dirname,'../../app/services/buildInfo.js'),'utf8').match(/const VERSION = '([^']+)'/)[1];
  const welcome=await browser.newPage();await welcome.goto(base+'/dist/xr/');
  await welcome.waitForSelector('.welcome-version-badge',{timeout:20000});
  const badge=await welcome.locator('.welcome-version-badge').textContent();assert.ok(badge.includes(version));
  await welcome.screenshot({path:path.join(__dirname,`welcome-${version}.png`)});
  const result={stage:2,assetBytes:bytes.length,stats,textures:asset.images.length,animationTracks:asset.animations[0].channels.length,checks:['embedded texture loading','no reference or cameras in GLB','single growth clip','new shoots reach mature scale','scrubbing changes rendered foliage','growth plays','pause freezes growth','replay and mature reset work','detail and side views','no preview page errors','built welcome version'],welcomeBadge:badge,headsetVerified:false};
  fs.writeFileSync(path.join(__dirname,'botanical-verification.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
